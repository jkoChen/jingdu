"""Pack original WenQuanYi 12/15 px BDF bitmaps and their per-character metrics."""

import argparse
from pathlib import Path


def read_glyphs(source, wanted):
    glyphs = {}
    for block in source.read_text(encoding="latin1").split("STARTCHAR ")[1:]:
        lines = block.splitlines()
        fields = {line.split()[0]: line.split()[1:] for line in lines if line.strip()}
        cp = int(fields["ENCODING"][0])
        if cp not in wanted:
            continue
        w, h, left, bottom = map(int, fields["BBX"])
        encoded = block.split("BITMAP", 1)[1].split("ENDCHAR", 1)[0].split()
        rows = [int(row, 16) >> ((-w) % 8) for row in encoded]
        assert len(rows) == h and 0 <= w <= 16
        glyphs[cp] = (int(fields["DWIDTH"][0]), left, bottom, w, h, rows)
    return glyphs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("bdf_directory", type=Path)
    ap.add_argument("output", type=Path)
    args = ap.parse_args()
    wanted = set(range(32, 127)) | set(map(ord, "℃°·—…↗←→✓□"))
    for lead in range(0xA1, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                wanted.add(ord(bytes([lead, trail]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    fonts = [
        read_glyphs(args.bdf_directory / name, wanted)
        for name in ("wenquanyi_9pt.bdf", "wenquanyi_11pt.bdf")
    ]
    chars = sorted(set(fonts[0]) & set(fonts[1]))
    assert 0x25A1 in chars and len(chars) > 7000
    with args.output.open("w", encoding="utf-8") as out:
        out.write(
            "// WenQuanYi Bitmap Song. Generated by scripts/ui_font.py; see licenses/WenQuanYi-COPYING.\n"
        )
        out.write("static const uint16_t codepoints[]={\n")
        for i in range(0, len(chars), 32):
            out.write(",".join(map(str, chars[i : i + 32])) + ",\n")
        out.write("};\n")
        for size, font in zip((12, 15), fonts):
            rows = []
            out.write(f"static const BitmapGlyph metrics{size}[]={{\n")
            for cp in chars:
                advance, x, bottom, w, h, r = font[cp]
                top = (11 if size == 12 else 13) - bottom - h
                out.write("{%d,%d,%d,%d,%d,%d},\n" % (len(rows), x, top, advance, w, h))
                rows.extend(row << (16 - w) for row in r)
            out.write("};\n")
            out.write(f"static const uint16_t rows{size}[]={{\n")
            for i in range(0, len(rows), 24):
                out.write(",".join(hex(n) for n in rows[i : i + 24]) + ",\n")
            out.write("};\n")


if __name__ == "__main__":
    main()
